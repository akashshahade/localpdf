export const toolMap = new Map(tools.map((t) => [t.slug, t]));
export const liveTools = tools.filter((t) => !t.comingSoon);

export function getTool(slug: string) {
  return toolMap.get(slug);
}

export function matchesTool(tool: Tool, query: string) {
  const tokens = `${tool.name} ${tool.short} ${tool.keywords ?? ""} ${tool.slug}`.toLowerCase().split(/[^a-z0-9]+/);
  return query
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean)
    .every((w) => tokens.some((t) => t.startsWith(w)));
}

export function getCategory(id: CategoryId) {
  return categories.find((c) => c.id === id)!;
}

export function getRelated(tool: Tool, count = 4) {
  return tools.filter((t) => t.category === tool.category && t.slug !== tool.slug).slice(0, count);
}

const followUps = ["compress-pdf", "sign-pdf", "page-numbers", "add-watermark", "encrypt-pdf", "merge-pdf"];
const photoFollowUps = ["resize-image-to-kb", "exam-photo-signature-resizer", "name-date-on-photo", "images-to-pdf", "resize-image"];

export function getNextSteps(tool: Tool) {
  const list = tool.output === "pdf" ? followUps : tool.output === "image" ? photoFollowUps : [];
  return list
    .filter((s) => s !== tool.slug)
    .slice(0, 4)
    .map((s) => toolMap.get(s)!);
}
